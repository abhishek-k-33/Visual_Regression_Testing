#!/usr/bin/env node
/**
 * Builds a read-only copy of the review dashboard for GitHub Pages, from real screenshots:
 *
 *   node scripts/build-static-demo.js --out _site --base /Visual_Regression_Testing
 *
 * 1. Serves the bundled demo site (scripts/demo-app.js) on a free port.
 * 2. Runs the real CLI five times against it, with all storage in a fresh temp folder
 *    (the repo's storage/ and committed baselines are never touched):
 *      demo-01-baseline   original   --update-baselines      -> PASSED (new baselines)
 *      demo-02-pass       original                           -> PASSED (match)
 *      demo-03-redesign   redesign   then approved here      -> APPROVED (new baseline)
 *      demo-04-pass       redesign                           -> PASSED (match)
 *      demo-05-regression regressed  left for visitors       -> FAILED (diff, pending)
 * 3. Renders index.html, runs/<id>.html, history/<slug>/<viewport>.html (one per route and
 *    viewport) and 404.html with the server's own templates in
 *    'static' mode (demo banner, simulated approve/reject), copies the CSS/JS and only
 *    the screenshots those pages reference.
 * 4. Checks the output: only expected file types, no database/manifests/summaries, and
 *    every local link resolves to a file in the output. Any problem fails the build.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import Database from 'better-sqlite3';
import { createDemoServer } from './demo-app.js';
import { normalizeBase } from '../src/server/urls.js';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLI = path.join(REPO_ROOT, 'src', 'cli', 'index.js');
const CONFIG = path.join(REPO_ROOT, 'scripts', 'pages-demo.config.json');
const PUBLIC_DIR = path.join(REPO_ROOT, 'src', 'server', 'public');
/** Public files that need the live server, never copied into the static build. */
export const LIVE_ONLY_ASSETS = new Set(['js/import-upload.js']);
const DEFAULT_REPO_URL = 'https://github.com/abhishek-k-33/Visual_Regression_Testing';

/** The runs the demo is made of, in order. `approve` approves every snapshot after the run. */
export const DEMO_RUNS = [
  { id: 'demo-01-baseline', variant: 'original', args: ['--update-baselines'], expect: { run: 'PASSED', snapshots: 'NEW_BASELINE' } },
  { id: 'demo-02-pass', variant: 'original', expect: { run: 'PASSED', snapshots: 'MATCH' } },
  {
    id: 'demo-03-redesign',
    variant: 'redesign',
    expect: { run: 'FAILED', snapshots: 'DIFF' },
    approve: true,
    expectAfterApprove: { run: 'APPROVED', snapshots: 'APPROVED' }
  },
  { id: 'demo-04-pass', variant: 'redesign', expect: { run: 'PASSED', snapshots: 'MATCH' } },
  { id: 'demo-05-regression', variant: 'regressed', expect: { run: 'FAILED', snapshots: 'DIFF' } }
];

// Everything the output may contain (paths relative to the output root, POSIX separators).
// Marks a folder as created by this script; only such folders are ever deleted.
const BUILD_MARKER = '.vrt-static-demo';
const BUILD_MARKER_CONTENT = 'Generated by scripts/build-static-demo.js; safe to delete and rebuild.\n';

const ALLOWED_OUTPUT_FILES = [
  /^(index|404)\.html$/,
  /^\.nojekyll$/,
  /^\.vrt-static-demo$/,
  /^runs\/[A-Za-z0-9_-]+\.html$/,
  /^history\/[A-Za-z0-9_-]+\/[A-Za-z0-9_-]+\.html$/,
  /^css\/[A-Za-z0-9_.-]+\.css$/,
  /^js\/[A-Za-z0-9_.-]+\.js$/,
  /^storage\/(runs|baselines)\/[A-Za-z0-9_\-./]+\.png$/
];
const FORBIDDEN_OUTPUT_FILES = [
  { pattern: /\.sqlite/i, why: 'database file' },
  { pattern: /\.db$/i, why: 'database file' },
  { pattern: /\.md$/i, why: 'Markdown summary' },
  { pattern: /(^|\/)run\.json$/i, why: 'run manifest' }
];
const SERVABLE_STORAGE_PATH = /^(runs|baselines)\/[A-Za-z0-9_\-./]+\.png$/;
const URL_ATTRIBUTE = /\s(?:href|src|action|formaction|poster|srcset)\s*=\s*(?:"([^"]*)"|'([^']*)')/gi;

// ─── small helpers ──────────────────────────────────────────────────────────

const log = (msg) => console.log(msg);

function listFiles(root) {
  const out = [];
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else out.push({ full, rel: path.relative(root, full).split(path.sep).join('/'), entry });
    }
  })(root);
  return out;
}

function decodeHtmlAttr(value) {
  return value
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&#x27;/gi, "'")
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
}

/** Every URL in href/src-like attributes of an HTML string (entity-decoded). */
export function extractUrls(html) {
  return [...html.matchAll(URL_ATTRIBUTE)].map((m) => decodeHtmlAttr(m[1] ?? m[2] ?? ''));
}

const isExternalOrFragment = (u) => /^(#|https?:|data:|mailto:)/i.test(u);

/**
 * Maps a local URL to the file GitHub Pages would serve for it, relative to the output
 * root: '<base>/' -> index.html, '<base>/runs/x' -> runs/x.html, '<base>/css/a.css' as is.
 * Returns { file } or { error }.
 */
export function resolveLocalUrl(url, base) {
  const prefix = `${base}/`;
  if (url.startsWith('//')) return { error: 'protocol-relative URL' };
  if (url !== base && !url.startsWith(prefix)) return { error: `does not start with the base "${prefix}"` };
  let p = url.slice(base.length).replace(/[?#].*$/, '') || '/';
  try {
    p = decodeURIComponent(p);
  } catch {
    return { error: 'malformed percent-encoding' };
  }
  const segments = p.split('/').filter(Boolean);
  if (segments.some((s) => s === '..' || s === '.')) return { error: 'contains . or .. segments' };
  if (p.endsWith('/')) segments.push('index.html');
  else if (!path.posix.extname(segments[segments.length - 1])) segments[segments.length - 1] += '.html';
  return { file: segments.join('/') };
}

/**
 * Checks a built site. Returns a list of problems (empty when the output is safe to publish).
 *
 * @param {string} outDir
 * @param {string} base - Normalized base path ('' or '/name')
 * @param {object} [options]
 * @param {string[]} [options.mustNotContain] - Strings no HTML page may contain (e.g. local paths)
 */
export function verifyOutput(outDir, base, { mustNotContain = [] } = {}) {
  const problems = [];
  const files = listFiles(outDir);
  const relSet = new Set(files.map((f) => f.rel));

  for (const required of ['index.html', '404.html', '.nojekyll', 'css/styles.css']) {
    if (!relSet.has(required)) problems.push(`missing required file: ${required}`);
  }

  for (const { rel, entry } of files) {
    if (!entry.isFile()) problems.push(`not a regular file (symlink?): ${rel}`);
    for (const { pattern, why } of FORBIDDEN_OUTPUT_FILES) {
      if (pattern.test(rel)) problems.push(`forbidden ${why} in output: ${rel}`);
    }
    if (!ALLOWED_OUTPUT_FILES.some((re) => re.test(rel)) || rel.split('/').includes('..')) {
      problems.push(`unexpected file in output: ${rel}`);
    }
  }

  for (const { full, rel } of files.filter((f) => f.rel.endsWith('.html'))) {
    const html = fs.readFileSync(full, 'utf8');
    if (!html.includes('data-mode="static"')) problems.push(`${rel}: not rendered in static mode`);
    for (const needle of mustNotContain) {
      if (needle && html.includes(needle)) problems.push(`${rel}: contains a local path (${needle})`);
    }
    for (const url of extractUrls(html)) {
      if (url === '') {
        problems.push(`${rel}: empty href/src`);
        continue;
      }
      if (isExternalOrFragment(url)) continue;
      const { file, error } = resolveLocalUrl(url, base);
      if (error) problems.push(`${rel}: ${url} ${error}`);
      else if (!relSet.has(file)) problems.push(`${rel}: ${url} -> ${file} does not exist in the output`);
    }
  }

  // ES module imports between the dashboard scripts must resolve too.
  for (const { full, rel } of files.filter((f) => f.rel.endsWith('.js'))) {
    const src = fs.readFileSync(full, 'utf8');
    for (const m of src.matchAll(/^\s*import\s[^'"]*['"]([^'"]+)['"]/gm)) {
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(rel), m[1]));
      if (!m[1].startsWith('./') || !relSet.has(target)) problems.push(`${rel}: import "${m[1]}" does not resolve`);
    }
  }

  return problems;
}

/** Total size in bytes and file count of a directory. */
export function dirStats(dir) {
  const files = listFiles(dir);
  return { files: files.length, bytes: files.reduce((sum, f) => sum + fs.statSync(f.full).size, 0) };
}

// ─── output folder ──────────────────────────────────────────────────────────

const isInsideOrEqual = (child, parent) => {
  const rel = path.relative(parent, child);
  return rel === '' || (rel.split(path.sep)[0] !== '..' && !path.isAbsolute(rel));
};

/** Empties (or creates) the output folder, refusing anything that isn't clearly a build folder. */
function prepareOutDir(outDir) {
  if (path.parse(outDir).root === outDir || outDir === os.homedir() || isInsideOrEqual(REPO_ROOT, outDir)) {
    throw new Error(`Refusing to use ${outDir} as the output folder (it contains the project or is a system folder).`);
  }
  for (const dir of ['src', 'scripts', 'storage', 'tests', 'node_modules', '.git', '.github', 'docs']) {
    if (isInsideOrEqual(outDir, path.join(REPO_ROOT, dir))) {
      throw new Error(`Refusing to write the site inside ${dir}/; choose a separate folder such as _site.`);
    }
  }
  if (fs.existsSync(outDir)) {
    if (!fs.statSync(outDir).isDirectory()) throw new Error(`${outDir} exists and is not a folder.`);
    const entries = fs.readdirSync(outDir);
    if (entries.includes('.git')) {
      throw new Error(`${outDir} is a git checkout (it has .git); refusing to delete it.`);
    }
    // .nojekyll alone is not proof: gh-pages checkouts and other docs folders have it too.
    const marker = path.join(outDir, BUILD_MARKER);
    const isOurs = fs.existsSync(marker) && fs.readFileSync(marker, 'utf8') === BUILD_MARKER_CONTENT;
    if (entries.length > 0 && !isOurs) {
      throw new Error(`${outDir} is not empty and doesn't look like a previous build (no ${BUILD_MARKER} marker); refusing to delete it.`);
    }
    fs.rmSync(outDir, { recursive: true, force: true });
  }
  fs.mkdirSync(outDir, { recursive: true });
  // Written first so a failed or partial build is still recognised as ours next time.
  fs.writeFileSync(path.join(outDir, BUILD_MARKER), BUILD_MARKER_CONTENT);
  fs.writeFileSync(path.join(outDir, '.nojekyll'), '');
}

// ─── running the CLI ────────────────────────────────────────────────────────

function runCli(args, env) {
  return new Promise((resolve) => {
    execFile(process.execPath, [CLI, 'test', ...args], { cwd: REPO_ROOT, env, maxBuffer: 16 * 1024 * 1024, timeout: 5 * 60 * 1000 }, (err, stdout, stderr) => {
      // A non-zero exit is expected for runs with diffs: outcomes are checked in the DB.
      resolve({ code: err ? (err.code ?? 1) : 0, output: `${stdout}${stderr}` });
    });
  });
}

function withDb(dbPath, fn) {
  if (!fs.existsSync(dbPath)) throw new Error(`No database was created at ${dbPath}`);
  const db = new Database(dbPath);
  try {
    return fn(db);
  } finally {
    db.close();
  }
}

function assertRunStatus(db, dbApi, run, expected, expectedSnapshots, cliOutput) {
  const row = dbApi.getTestRunById(run.id, db);
  const snapshots = dbApi.getSnapshotsByRunId(run.id, db);
  const problems = [];
  if (!row) problems.push('run was not recorded');
  else if (row.status !== expected.run) problems.push(`run status ${row.status}, expected ${expected.run}`);
  if (snapshots.length !== expectedSnapshots) problems.push(`${snapshots.length} snapshot(s), expected ${expectedSnapshots}`);
  for (const s of snapshots) {
    if (s.status !== expected.snapshots) problems.push(`${s.route} @ ${s.viewport}: ${s.status}, expected ${expected.snapshots}`);
  }
  if (problems.length) {
    const tail = cliOutput ? `\n--- CLI output ---\n${cliOutput.trim().split('\n').slice(-40).join('\n')}` : '';
    throw new Error(`Run ${run.id} did not produce the expected result:\n  - ${problems.join('\n  - ')}${tail}`);
  }
  return snapshots;
}

/**
 * Runs the demo scenario into `storageRoot` and returns nothing; throws if any run's
 * outcome isn't the expected one.
 */
async function recordDemoRuns(storageRoot, dbApi) {
  const config = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
  const expectedSnapshots = config.routes.length * config.viewports.length;
  const dbPath = path.join(storageRoot, 'data.sqlite');

  const env = { ...process.env, VISUAL_STORAGE_DIR: storageRoot };
  delete env.CI; // CI=true would make the CLI strict; the demo creates its own baselines
  delete env.GITHUB_STEP_SUMMARY; // keep the demo's summaries out of the workflow's step summary

  let variant = 'original';
  const server = createDemoServer(() => variant);
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  const baseUrl = `http://127.0.0.1:${server.address().port}`;
  log(`Demo site on ${baseUrl}; storage in ${storageRoot}`);

  try {
    for (const run of DEMO_RUNS) {
      variant = run.variant;
      log(`▶ ${run.id} (${run.variant} page)`);
      const { code, output } = await runCli(
        ['-c', CONFIG, '-u', baseUrl, '-r', run.id, '--no-strict', ...(run.args || [])],
        env
      );
      withDb(dbPath, (db) => assertRunStatus(db, dbApi, run, run.expect, expectedSnapshots, output));
      log(`  ${run.expect.run} (CLI exit ${code}), snapshots ${run.expect.snapshots}`);

      if (run.approve) {
        withDb(dbPath, (db) => {
          for (const s of dbApi.getSnapshotsByRunId(run.id, db)) dbApi.approveSnapshot(s.id, db, { storageRoot });
          assertRunStatus(db, dbApi, run, run.expectAfterApprove, expectedSnapshots);
        });
        log(`  approved -> ${run.expectAfterApprove.run} (the redesign is now the baseline)`);
      }
    }
  } finally {
    await new Promise((resolve) => server.close(resolve));
  }
}

// ─── rendering ──────────────────────────────────────────────────────────────

async function renderSite({ outDir, base, repoUrl, storageRoot }) {
  const { default: app } = await import('../src/server/app.js');
  const { pageLocals } = await import('../src/server/urls.js');
  const { indexModel, runDetailModel, historyModel, historyPath } = await import('../src/server/viewModels.js');
  const { getRouteViewportPairs } = await import('../src/server/db.js');

  const locals = { ...pageLocals({ base, mode: 'static' }), repoUrl };
  const render = (view, model) => new Promise((resolve, reject) => {
    // Render options only: app.locals (shared with live requests) is never changed.
    app.render(view, { ...model, ...locals }, (err, html) => (err ? reject(err) : resolve(html)));
  });
  const write = (rel, html) => {
    const file = path.join(outDir, ...rel.split('/'));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html);
  };

  // Read every model first (synchronous DB access), then render.
  const { index, details, histories } = withDb(path.join(storageRoot, 'data.sqlite'), (db) => {
    const model = indexModel({ db });
    // One history page per route slug + viewport, at the same path the run pages link to.
    const historyPages = new Map();
    for (const { route, viewport } of getRouteViewportPairs(db)) {
      const page = historyPath(route, viewport);
      if (!page || historyPages.has(page)) continue;
      const [, , slug] = page.split('/');
      historyPages.set(page, historyModel({ db, slug, viewport, storageRoot }));
    }
    return {
      index: model,
      details: model.runs.map((run) => runDetailModel({ db, runId: run.id, storageRoot })),
      histories: historyPages
    };
  });
  write('index.html', await render('index', index));
  for (const detail of details) {
    const { id } = detail.run;
    if (!/^[A-Za-z0-9_-]+$/.test(id)) throw new Error(`Run id "${id}" is not safe as a file name`);
    write(`runs/${id}.html`, await render('run-detail', detail));
  }
  for (const [page, model] of histories) {
    if (!model) throw new Error(`No history found for ${page}`);
    // historyPath() only produces /history/<[A-Za-z0-9_-]+>/<[A-Za-z0-9_-]+>
    write(`${page.slice(1)}.html`, await render('history', model));
  }
  log(`Rendered index.html, ${details.length} run pages and ${histories.size} history pages`);

  write('404.html', await render('layout', {
    title: 'Page not found',
    heading: 'Page not found',
    message: 'That page is not part of this demo. Use the Dashboard link above to browse the sample runs.'
  }));

  // Dashboard CSS and JS (not .gitkeep or anything else in public/). Scripts that only
  // make sense with a server (importing a CI run) are left out of the read-only build.
  for (const { full, rel } of listFiles(PUBLIC_DIR)) {
    if (!/\.(css|js)$/.test(rel) || LIVE_ONLY_ASSETS.has(rel)) continue;
    const dest = path.join(outDir, ...rel.split('/'));
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(full, dest);
  }

  copyReferencedScreenshots({ outDir, base, storageRoot });
}

/** Copies exactly the PNGs the rendered pages reference into <out>/storage/... */
function copyReferencedScreenshots({ outDir, base, storageRoot }) {
  const prefix = `${base}/storage/`;
  const wanted = new Set();
  for (const { full } of listFiles(outDir).filter((f) => f.rel.endsWith('.html'))) {
    for (const url of extractUrls(fs.readFileSync(full, 'utf8'))) {
      if (url.startsWith(prefix)) wanted.add(decodeURIComponent(url.slice(prefix.length)));
    }
  }

  const realStorage = fs.realpathSync(storageRoot);
  for (const rel of wanted) {
    if (!SERVABLE_STORAGE_PATH.test(rel) || rel.split('/').includes('..')) {
      throw new Error(`Refusing to publish storage file "${rel}" (only PNGs under runs/ or baselines/)`);
    }
    const source = path.join(storageRoot, ...rel.split('/'));
    if (!fs.existsSync(source) || !fs.lstatSync(source).isFile()) {
      throw new Error(`A page references /storage/${rel}, but it is not a file in the demo storage`);
    }
    if (!isInsideOrEqual(fs.realpathSync(source), realStorage)) throw new Error(`/storage/${rel} resolves outside the demo storage`);
    const dest = path.join(outDir, 'storage', ...rel.split('/'));
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(source, dest);
  }
  log(`Copied ${wanted.size} referenced screenshots`);
}

// ─── entry point ────────────────────────────────────────────────────────────

function defaultRepoUrl() {
  const { GITHUB_SERVER_URL, GITHUB_REPOSITORY } = process.env;
  return GITHUB_SERVER_URL && GITHUB_REPOSITORY ? `${GITHUB_SERVER_URL}/${GITHUB_REPOSITORY}` : DEFAULT_REPO_URL;
}

/**
 * Builds the static demo site.
 *
 * @param {{ out: string, base?: string, repoUrl?: string }} options
 * @returns {Promise<{ outDir: string, base: string, files: number, bytes: number }>}
 */
export async function buildStaticDemo({ out, base = '', repoUrl = defaultRepoUrl() }) {
  if (!out) throw new Error('--out is required');
  if (!/^https:\/\/[^\s"'<>]+$/.test(repoUrl)) throw new Error(`--repo-url must be an https URL, got "${repoUrl}"`);
  const outDir = path.resolve(out);
  const normalizedBase = normalizeBase(base);
  if (!/^(\/[A-Za-z0-9._-]+)*$/.test(normalizedBase)) throw new Error(`Unsupported --base "${base}"`);

  const dbApi = await import('../src/server/db.js');
  prepareOutDir(outDir);
  const storageRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'vrt-pages-demo-'));
  try {
    await recordDemoRuns(storageRoot, dbApi);
    await renderSite({ outDir, base: normalizedBase, repoUrl, storageRoot });

    const problems = verifyOutput(outDir, normalizedBase, { mustNotContain: [storageRoot, fs.realpathSync(storageRoot), REPO_ROOT] });
    if (problems.length) throw new Error(`Safety checks failed:\n  - ${problems.join('\n  - ')}`);
  } catch (err) {
    // Never leave a half-built or unsafe site where it could be published.
    fs.rmSync(outDir, { recursive: true, force: true });
    throw err;
  } finally {
    fs.rmSync(storageRoot, { recursive: true, force: true });
  }

  return { outDir, base: normalizedBase, ...dirStats(outDir) };
}

async function main() {
  const { values } = parseArgs({
    options: {
      out: { type: 'string', default: '_site' },
      base: { type: 'string', default: '' },
      'repo-url': { type: 'string' }
    }
  });
  const result = await buildStaticDemo({ out: values.out, base: values.base, repoUrl: values['repo-url'] || undefined });
  log(`\n✓ Static demo built in ${path.relative(process.cwd(), result.outDir) || '.'}: ` +
    `${result.files} files, ${(result.bytes / 1024).toFixed(1)} KiB, base "${result.base || '/'}"`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(`\n[ERROR] Static demo build failed: ${err.message}\n`);
    process.exit(1);
  });
}
